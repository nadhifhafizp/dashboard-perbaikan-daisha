-- ============================================================================
-- Dashboard Perbaikan Daisha - Proposed PostgreSQL Schema V2 (13 tables)
-- PostgreSQL 15+ / Supabase
--
-- PENTING:
-- 1. Ini skema target baru. Dijalankan berdampingan dengan tabel lama (non-destruktif).
-- 2. Tidak menghapus/mengubah tabel lama.
-- 3. DaishaCatalog.components dan .variants dipertahankan sebagai JSONB karena
--    aplikasi saat ini mengelola konfigurasi katalog sebagai dokumen JSON.
-- 4. Transaksi operasional (ticket item, approval, material, stok) dinormalisasi.
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. MASTER SEKSI
CREATE TABLE IF NOT EXISTS sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  color_name VARCHAR(50),
  badge_bg VARCHAR(50),
  text_color VARCHAR(50),
  border_color VARCHAR(50),
  accent_border VARCHAR(50),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sections_name_ci
  ON sections (LOWER(TRIM(name)));

-- 2. PENGGUNA
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  full_name VARCHAR(255) NOT NULL,
  role VARCHAR(30) NOT NULL
    CHECK (role IN ('ADMIN', 'OPERATOR', 'USER_SEKSI')),
  section_id BIGINT REFERENCES sections(id) ON DELETE SET NULL,
  legacy_section_name VARCHAR(100),
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_users_section ON users(section_id);

-- 3. KATALOG DAISHA
CREATE TABLE IF NOT EXISTS daisha_catalogs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  section_id BIGINT REFERENCES sections(id) ON DELETE SET NULL,
  legacy_section_name VARCHAR(100),
  code_prefix VARCHAR(50),
  total_units INTEGER NOT NULL DEFAULT 0 CHECK (total_units >= 0),
  components JSONB NOT NULL DEFAULT '[]'::jsonb,
  variants JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_daisha_catalogs_name_ci
  ON daisha_catalogs (LOWER(TRIM(name)));

CREATE SEQUENCE IF NOT EXISTS "DaishaComponent_id_seq" START WITH 300;
CREATE SEQUENCE IF NOT EXISTS "DaishaSymptom_id_seq" START WITH 600;
CREATE SEQUENCE IF NOT EXISTS "DaishaVariant_id_seq" START WITH 100;

-- 4. UNIT FISIK DAISHA
CREATE TABLE IF NOT EXISTS daisha_units (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  catalog_id BIGINT REFERENCES daisha_catalogs(id) ON DELETE SET NULL,
  section_id BIGINT REFERENCES sections(id) ON DELETE SET NULL,
  nomor_daisha TEXT NOT NULL UNIQUE,
  nama_daisha TEXT,
  jenis TEXT NOT NULL,
  ukuran TEXT NOT NULL,
  legacy_section_name VARCHAR(100),
  last_condition TEXT NOT NULL DEFAULT 'OK',
  last_maintenance_date TIMESTAMPTZ,
  last_repair_date TIMESTAMPTZ,
  last_waktu_masuk TIMESTAMPTZ,
  last_waktu_keluar TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_daisha_units_catalog ON daisha_units(catalog_id);
CREATE INDEX IF NOT EXISTS idx_daisha_units_section ON daisha_units(section_id);
CREATE INDEX IF NOT EXISTS idx_daisha_units_type_size ON daisha_units(jenis, ukuran);
CREATE INDEX IF NOT EXISTS idx_daisha_units_condition ON daisha_units(last_condition);

-- 5. TIKET PERBAIKAN
CREATE TABLE IF NOT EXISTS repair_tickets (
  id_ticket VARCHAR(100) PRIMARY KEY,
  daisha_id UUID REFERENCES daisha_units(id) ON DELETE RESTRICT,
  nomor_daisha_snapshot TEXT NOT NULL,
  reporter_name VARCHAR(150) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Open'
    CHECK (status IN ('Queue', 'Open', 'Progress', 'Pending', 'Done', 'Scrap')),
  opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  notes TEXT,
  legacy_items JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_repair_tickets_daisha ON repair_tickets(daisha_id);
CREATE INDEX IF NOT EXISTS idx_repair_tickets_status ON repair_tickets(status);
CREATE INDEX IF NOT EXISTS idx_repair_tickets_opened_at ON repair_tickets(opened_at DESC);

-- 6. ITEM / DETAIL TIKET
CREATE TABLE IF NOT EXISTS repair_ticket_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id VARCHAR(100) NOT NULL REFERENCES repair_tickets(id_ticket) ON DELETE CASCADE,
  component_name VARCHAR(255),
  symptom TEXT,
  action VARCHAR(100),
  quantity NUMERIC(14,3) NOT NULL DEFAULT 1 CHECK (quantity > 0),
  sort_order INTEGER NOT NULL DEFAULT 0,
  source_type VARCHAR(30) NOT NULL DEFAULT 'MIGRATED',
  legacy_detail_id BIGINT,
  source_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_repair_ticket_items_ticket ON repair_ticket_items(ticket_id);

-- 7. RIWAYAT MAINTENANCE / PM / REPAIR
CREATE TABLE IF NOT EXISTS maintenance_logs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  daisha_id UUID NOT NULL REFERENCES daisha_units(id) ON DELETE RESTRICT,
  source_ticket_id VARCHAR(100) REFERENCES repair_tickets(id_ticket) ON DELETE SET NULL,
  nomor_daisha_snapshot TEXT NOT NULL,
  jenis_pekerjaan VARCHAR(50) NOT NULL,
  kondisi TEXT,
  detail_kerusakan TEXT,
  tindakan TEXT,
  tanggal_pengerjaan TIMESTAMPTZ NOT NULL,
  waktu_masuk TIMESTAMPTZ,
  waktu_keluar TIMESTAMPTZ,
  performed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  performed_by_snapshot TEXT,
  catatan TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_maintenance_logs_daisha ON maintenance_logs(daisha_id);
CREATE INDEX IF NOT EXISTS idx_maintenance_logs_date ON maintenance_logs(tanggal_pengerjaan DESC);
CREATE INDEX IF NOT EXISTS idx_maintenance_logs_ticket ON maintenance_logs(source_ticket_id);

-- 8. PENGAJUAN SEKSI
CREATE TABLE IF NOT EXISTS section_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_number VARCHAR(100) NOT NULL UNIQUE,
  official_number VARCHAR(100) UNIQUE,
  section_id BIGINT REFERENCES sections(id) ON DELETE SET NULL,
  requester_section_snapshot VARCHAR(100) NOT NULL,
  requester_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  requester_name VARCHAR(150) NOT NULL,
  requester_contact VARCHAR(100),
  item_name VARCHAR(255) NOT NULL,
  specification TEXT,
  quantity NUMERIC(14,3) NOT NULL DEFAULT 1,
  unit VARCHAR(50) NOT NULL DEFAULT 'Pcs',
  urgency VARCHAR(50) NOT NULL DEFAULT 'Normal',
  factor VARCHAR(100),
  purpose TEXT,
  reason TEXT,
  notes TEXT,
  status VARCHAR(100) NOT NULL DEFAULT 'Menunggu Assign Atasan Seksi',
  flow_step VARCHAR(100) NOT NULL DEFAULT 'STEP_2_WAITING_ATASAN_SEKSI',
  workshop_pic VARCHAR(150),
  admin_note TEXT,
  rejection_reason TEXT,
  pending_reason TEXT,
  completed_at TIMESTAMPTZ,
  form_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by_snapshot VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_section_requests_status ON section_requests(status);
CREATE INDEX IF NOT EXISTS idx_section_requests_section ON section_requests(section_id);
CREATE INDEX IF NOT EXISTS idx_section_requests_created ON section_requests(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_section_requests_flow ON section_requests(flow_step);

-- 9. RIWAYAT PERSETUJUAN / REVIEW REQUEST
CREATE TABLE IF NOT EXISTS section_request_approvals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES section_requests(id) ON DELETE CASCADE,
  stage VARCHAR(40) NOT NULL
    CHECK (stage IN ('SECTION_SUPERVISOR', 'SECTION_MANAGER', 'WORKSHOP', 'SPECIAL_PROJECT')),
  approval_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  reviewer_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  reviewer_name VARCHAR(150),
  reviewer_email VARCHAR(255),
  decision VARCHAR(100),
  decision_8210 VARCHAR(100),
  decision_820 VARCHAR(100),
  approval_token TEXT,
  signature_data TEXT,
  approved_at TIMESTAMPTZ,
  notes TEXT,
  source_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_request_approvals_request ON section_request_approvals(request_id);
CREATE INDEX IF NOT EXISTS idx_request_approvals_stage_status ON section_request_approvals(stage, approval_status);
CREATE UNIQUE INDEX IF NOT EXISTS uq_request_approval_token
  ON section_request_approvals(approval_token) WHERE approval_token IS NOT NULL;

-- 10. INVENTARIS SPAREPART
CREATE TABLE IF NOT EXISTS spareparts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  category VARCHAR(100) NOT NULL DEFAULT 'Umum',
  stock_quantity NUMERIC(14,3) NOT NULL DEFAULT 0,
  unit VARCHAR(50) NOT NULL DEFAULT 'Pcs',
  minimum_stock NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (minimum_stock >= 0),
  location VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_spareparts_category ON spareparts(category);

-- 11. MATERIAL / SPAREPART YANG DIPAKAI PADA REQUEST
CREATE TABLE IF NOT EXISTS section_request_materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES section_requests(id) ON DELETE CASCADE,
  sparepart_id BIGINT REFERENCES spareparts(id) ON DELETE SET NULL,
  item_name_snapshot VARCHAR(255) NOT NULL,
  item_type VARCHAR(20) NOT NULL DEFAULT 'SPAREPART'
    CHECK (item_type IN ('SPAREPART', 'MATERIAL')),
  specification TEXT,
  quantity NUMERIC(14,3) NOT NULL DEFAULT 1,
  unit VARCHAR(50) NOT NULL DEFAULT 'Pcs',
  dimensions VARCHAR(100),
  deduct_stock BOOLEAN NOT NULL DEFAULT FALSE,
  deducted_quantity NUMERIC(14,3) NOT NULL DEFAULT 0,
  notes TEXT,
  source_type VARCHAR(30) NOT NULL DEFAULT 'MIGRATED',
  source_legacy_id TEXT,
  source_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_request_materials_request ON section_request_materials(request_id);
CREATE INDEX IF NOT EXISTS idx_request_materials_sparepart ON section_request_materials(sparepart_id);

-- 12. NOTIFIKASI REQUEST
CREATE TABLE IF NOT EXISTS section_request_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT REFERENCES section_requests(id) ON DELETE CASCADE,
  request_number_snapshot VARCHAR(100),
  target_role VARCHAR(50),
  target_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  target_user_snapshot VARCHAR(100),
  target_email VARCHAR(255),
  notification_type VARCHAR(100),
  title VARCHAR(255) NOT NULL,
  message TEXT NOT NULL,
  link TEXT,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_request_notifications_user_read
  ON section_request_notifications(target_user_id, is_read);
CREATE INDEX IF NOT EXISTS idx_request_notifications_request
  ON section_request_notifications(request_id);

-- 13. MUTASI STOK SPAREPART
CREATE TABLE IF NOT EXISTS sparepart_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sparepart_id BIGINT REFERENCES spareparts(id) ON DELETE SET NULL,
  sparepart_name_snapshot VARCHAR(255) NOT NULL,
  movement_type VARCHAR(20) NOT NULL
    CHECK (movement_type IN ('IN', 'OUT', 'ADJUSTMENT')),
  quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
  reference_type VARCHAR(30) NOT NULL DEFAULT 'MANUAL'
    CHECK (reference_type IN ('MANUAL', 'REPAIR_TICKET', 'SECTION_REQUEST', 'LEGACY')),
  reference_value VARCHAR(150),
  request_id BIGINT REFERENCES section_requests(id) ON DELETE SET NULL,
  ticket_id VARCHAR(100) REFERENCES repair_tickets(id_ticket) ON DELETE SET NULL,
  performed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  performed_by_snapshot VARCHAR(100),
  note TEXT,
  source_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  moved_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sparepart_movements_sparepart ON sparepart_movements(sparepart_id);
CREATE INDEX IF NOT EXISTS idx_sparepart_movements_date ON sparepart_movements(moved_at DESC);
CREATE INDEX IF NOT EXISTS idx_sparepart_movements_reference ON sparepart_movements(reference_type, reference_value);
